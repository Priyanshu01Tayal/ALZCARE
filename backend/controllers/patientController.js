// @desc    Change password for authenticated patient
// @route   PUT /api/patients/me/password
// @access  Private/Patient
const changePatientPassword = async (req, res) => {
  const { currentPassword, newPassword } = req.body;

  try {
    if (req.role !== 'Patient') {
      return res.status(403).json({ message: 'Only patients can change their patient password' });
    }

    if (!newPassword || newPassword.length < 6) {
      return res.status(400).json({ message: 'New password must be at least 6 characters long' });
    }

    const patient = await Patient.findById(req.user._id);
    if (!patient) {
      return res.status(404).json({ message: 'Patient not found' });
    }

    // If current password provided, verify it (unless first-time temporary password change)
    if (currentPassword) {
      const isMatch = await patient.matchPassword(currentPassword);
      if (!isMatch) {
        return res.status(400).json({ message: 'Current password is incorrect' });
      }
    }

    patient.password = newPassword.trim();
    patient.mustChangePassword = false;
    await patient.save();

    await logActivity(
      patient._id,
      'Patient',
      'Password Changed',
      `Patient ${patient.name} updated account password`
    );

    res.json({ message: 'Password successfully updated' });
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

