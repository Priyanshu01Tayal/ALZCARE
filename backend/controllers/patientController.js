// @desc    Get patient detailed clinical records
// @route   GET /api/patients/:id
// @access  Private (Doctor or Patient themselves)
const getPatientById = async (req, res) => {
  try {
    const patient = await Patient.findById(req.params.id).select('-password');

    if (!patient) {
      return res.status(404).json({ message: 'Patient not found' });
    }

    // Role-based authorization
    if (req.role === 'Doctor' && patient.doctorId.toString() !== req.user._id.toString()) {
      return res.status(403).json({ message: 'Not authorized to view this patient' });
    }
    if (req.role === 'Patient' && patient._id.toString() !== req.user._id.toString()) {
      return res.status(403).json({ message: 'Not authorized to view this record' });
    }

    const doctor = await Doctor.findById(patient.doctorId).select('name email specialization');
    const prescriptions = await Prescription.find({ patientId: patient._id }).sort({ date: -1 });
    const mris = await MriReport.find({ patientId: patient._id }).sort({ createdAt: -1 });
    const games = await GameAssignment.find({ patientId: patient._id }).sort({ assignedAt: -1 });
    const appointments = await Appointment.find({ patientId: patient._id }).sort({ date: 1 });
    const gameResults = await GameResult.find({ patientId: patient._id }).sort({ completionDate: -1 });
    const recentActivity = await ActivityLog.find({ userId: patient._id }).sort({ createdAt: -1 }).limit(10);

    const latestGame = gameResults[0] || null;
    const mobileActivity = {
      lastActive: patient.lastActive || patient.updatedAt,
      lastGame: latestGame ? {
        gameName: latestGame.gameName,
        score: latestGame.score,
        accuracy: latestGame.accuracy,
        timeTaken: latestGame.timeTaken,
        completed: true,
        completionDate: latestGame.completionDate,
      } : null,
      score: latestGame ? latestGame.score : 0,
      attempts: gameResults.length,
      completedCount: games.filter((g) => g.status === 'Completed').length,
      activeAssignmentsCount: games.filter((g) => g.status === 'Assigned').length,
    };

    res.json({
      patient,
      doctor,
      prescriptions,
      mris,
      games,
      gameResults,
      appointments,
      mobileActivity,
      recentActivity,
    });
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

// @desc    Add a patient (Doctor only)
// @route   POST /api/patients
// @access  Private/Doctor
const addPatient = async (req, res) => {
  const { name, email, password, age, gender, medicalHistory, status } = req.body;

  try {
    if (!name || !email || !age || !gender) {
      return res.status(400).json({ message: 'Name, email, age, and gender are required' });
    }

    const normalizedEmail = email.trim().toLowerCase();

    // Check if user exists
    const patientExists = await Patient.findOne({ email: normalizedEmail });
    const doctorExists = await Doctor.findOne({ email: normalizedEmail });

    if (patientExists || doctorExists) {
      return res.status(400).json({ message: 'A user account already exists with this email address' });
    }

    // Generate secure temporary password if none provided
    const isAutoGenerated = !password || password.trim() === '';
    const rawPassword = isAutoGenerated
      ? `AlzCare#${Math.floor(100000 + Math.random() * 900000)}`
      : password.trim();

    const patient = await Patient.create({
      name: name.trim(),
      email: normalizedEmail,
      password: rawPassword,
      age: Number(age),
      gender,
      medicalHistory: medicalHistory || '',
      phone: req.body.phone || '',
      address: req.body.address || '',
      emergencyContact: req.body.emergencyContact || { name: '', phone: '', relation: '' },
      status: status && ['Active', 'Inactive', 'Pending'].includes(status) ? status : 'Active',
      mustChangePassword: isAutoGenerated,
      doctorId: req.user._id,
    });

    if (patient) {
      // Create a notification for the patient
      await Notification.create({
        userId: patient._id,
        userType: 'Patient',
        message: `Welcome to AlzCare! Dr. ${req.user.name} has created your profile. You can log in with your credentials.`,
      });

      await logActivity(
        req.user._id,
        'Doctor',
        'Patient Registered',
        `Patient ${patient.name} (${patient.patientId}) was registered by Dr. ${req.user.name}`
      );

      const patientObj = {
        _id: patient._id,
        name: patient.name,
        email: patient.email,
        age: patient.age,
        gender: patient.gender,
        medicalHistory: patient.medicalHistory,
        doctorId: patient.doctorId,
        patientId: patient.patientId,
        status: patient.status,
        mustChangePassword: patient.mustChangePassword,
      };

      res.status(201).json({
        ...patientObj,
        patient: patientObj,
        initialCredentials: {
          name: patient.name,
          patientId: patient.patientId,
          email: patient.email,
          temporaryPassword: rawPassword,
          mustChangePassword: patient.mustChangePassword,
        },
      });
    } else {
      res.status(400).json({ message: 'Invalid patient data' });
    }
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

// @desc    Update patient details (Doctor only)
// @route   PUT /api/patients/:id
// @access  Private/Doctor
const updatePatient = async (req, res) => {
  try {
    const patient = await Patient.findById(req.params.id);

    if (!patient) {
      return res.status(404).json({ message: 'Patient not found' });
    }

    // Verify ownership
    if (patient.doctorId.toString() !== req.user._id.toString()) {
      return res.status(403).json({ message: 'Not authorized to modify this patient' });
    }

    patient.name = req.body.name || patient.name;
    patient.age = req.body.age !== undefined ? Number(req.body.age) : patient.age;
    patient.gender = req.body.gender || patient.gender;
    patient.medicalHistory = req.body.medicalHistory !== undefined ? req.body.medicalHistory : patient.medicalHistory;
    if (req.body.status && ['Active', 'Inactive', 'Pending'].includes(req.body.status)) {
      patient.status = req.body.status;
    }
    if (req.body.phone !== undefined) patient.phone = req.body.phone;
    if (req.body.address !== undefined) patient.address = req.body.address;
    if (req.body.emergencyContact !== undefined) patient.emergencyContact = req.body.emergencyContact;

    // Only update email if it doesn't clash
    if (req.body.email && req.body.email.trim().toLowerCase() !== patient.email) {
      const normalizedNewEmail = req.body.email.trim().toLowerCase();
      const emailExists = await Patient.findOne({ email: normalizedNewEmail }) || await Doctor.findOne({ email: normalizedNewEmail });
      if (emailExists) {
        return res.status(400).json({ message: 'Email already in use by another user' });
      }
      patient.email = normalizedNewEmail;
    }

    // Update password if provided
    if (req.body.password && req.body.password.trim()) {
      patient.password = req.body.password.trim();
      patient.mustChangePassword = false;
    }

    const updatedPatient = await patient.save();

    await logActivity(
      req.user._id,
      'Doctor',
      'Patient Profile Updated',
      `Patient ${updatedPatient.name} (${updatedPatient.patientId}) profile updated by Dr. ${req.user.name}`
    );

    res.json({
      _id: updatedPatient._id,
      name: updatedPatient.name,
      email: updatedPatient.email,
      age: updatedPatient.age,
      gender: updatedPatient.gender,
      medicalHistory: updatedPatient.medicalHistory,
      status: updatedPatient.status,
      patientId: updatedPatient.patientId,
      phone: updatedPatient.phone,
      address: updatedPatient.address,
      emergencyContact: updatedPatient.emergencyContact,
    });
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

// @desc    Delete patient (Doctor only)
// @route   DELETE /api/patients/:id
// @access  Private/Doctor
const deletePatient = async (req, res) => {
  try {
    const patient = await Patient.findById(req.params.id);

    if (!patient) {
      return res.status(404).json({ message: 'Patient not found' });
    }

    // Verify ownership
    if (patient.doctorId.toString() !== req.user._id.toString()) {
      return res.status(403).json({ message: 'Not authorized to delete this patient' });
    }

    await Patient.findByIdAndDelete(req.params.id);
    
    // Clean up patient documents
    await Prescription.deleteMany({ patientId: req.params.id });
    await MriReport.deleteMany({ patientId: req.params.id });
    await GameAssignment.deleteMany({ patientId: req.params.id });
    await Appointment.deleteMany({ patientId: req.params.id });
    await Notification.deleteMany({ userId: req.params.id });

    await logActivity(
      req.user._id,
      'Doctor',
      'Patient Deleted',
      `Patient ${patient.name} (${patient.patientId}) and all linked records deleted by Dr. ${req.user.name}`
    );

    res.json({ message: 'Patient and all associated records removed' });
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

